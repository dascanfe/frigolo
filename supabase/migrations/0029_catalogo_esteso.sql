-- 3. i prodotti base di pesce passano alla categoria "pesce"
with moved as (
  update public.items i
  set category_id = (select id from public.categories where slug = 'pesce')
  where i.household_id is null
    and i.name in ('Salmone', 'Merluzzo', 'Orata', 'Branzino', 'Tonno fresco', 'Gamberi', 'Cozze', 'Vongole', 'Calamari')
    and i.category_id is distinct from (select id from public.categories where slug = 'pesce')
  returning i.id
)
update public.purchases p
set category_id = (select id from public.categories where slug = 'pesce')
from moved
where p.item_id = moved.id;

