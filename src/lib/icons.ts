export type IconName = keyof typeof ICONS

/** Tutti i nomi disponibili, in ordine alfabetico (per il picker) */
export const ICON_NAMES = Object.keys(ICONS) as IconName[]

/** Icona usata quando il nome salvato non è nel catalogo */
export const FALLBACK_ICON: IconName = 'ShoppingBasket'

export function isIconName(name: string): name is IconName {
  return Object.hasOwn(ICONS, name)
}

/** Risolve un nome in componente, con fallback sicuro per nomi sconosciuti */
export function getIcon(name: string | null | undefined): LucideIcon {
  if (name && isIconName(name)) return ICONS[name]
  return ICONS[FALLBACK_ICON]
}
