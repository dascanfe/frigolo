describe('icone in uso nel database', () => {
  it('ogni nome in uso è nel catalogo, nessuno ricade sul ripiego per errore', () => {
    const mancanti = ICONE_IN_USO.filter((name) => !isIconName(name))
    expect(mancanti).toEqual([])
    for (const name of ICONE_IN_USO) {
      if (name === FALLBACK_ICON) continue
      expect(getIcon(name), name).not.toBe(getIcon(FALLBACK_ICON))
    }
  })
})

describe('icone con nomi imprevisti', () => {
  it.each([
    null,
    undefined,
    '',
    ' ',
    'constructor',
    '__proto__',
    'toString',
    'hasOwnProperty',
    'valueOf',
    'shoppingbasket',
    'Beef ',
    '🍎',
    'A'.repeat(40),
  ])('%j ricade sul ripiego senza lanciare', (name) => {
    expect(getIcon(name)).toBe(getIcon(FALLBACK_ICON))
  })
})
